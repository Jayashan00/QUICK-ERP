import assert from 'node:assert/strict';
import { getPermissionsForScope } from '@/core/permissions';
import { dashboardService } from '@/features/dashboard/services/dashboardService';
import { salesService } from '@/features/sales/services/salesService';
import { inventoryService } from '@/features/inventory/services/inventoryService';
import { accountingService } from '@/features/accounting/accountingService';
import { periodRange, previousRange, trend } from '@/features/dashboard/utils/period';
import type { DashboardFilters } from '@/features/dashboard/types/dashboard';

Object.defineProperty(globalThis, 'window', { value: globalThis, configurable: true });
const filters: DashboardFilters = { tenantId: 'tenant-001', branchId: 'branch-001', permittedBranchIds: ['branch-001', 'branch-002'], permissions: getPermissionsForScope('tenant'), userId: 'user-001', period: 'custom', dateFrom: '2026-01-01', dateTo: '2026-12-31' };
const load = (changes: Partial<DashboardFilters> = {}) => dashboardService.getDashboardOverview({ ...filters, ...changes });
const data = await load();
assert.deepEqual(data.errors, [], 'all permitted sources must load');
assert.ok(data.metrics.length <= 6);
assert.ok(data.approvals.length <= 5 && data.alerts.length <= 5 && (data.activity?.length ?? 0) <= 6);
const scope = { tenantId: filters.tenantId, branchId: filters.branchId };
const source = (await salesService.listInvoices(scope, { permittedBranchIds: filters.permittedBranchIds, branchId: filters.branchId, pageSize: Number.MAX_SAFE_INTEGER })).data;
const eligible = source.filter(row => !['draft', 'void', 'cancelled'].includes(row.status) && row.invoiceDate >= filters.dateFrom && row.invoiceDate <= filters.dateTo);
const revenue = eligible.reduce((sum, row) => sum + row.totalAmount, 0);
assert.equal(data.metrics.find(row => row.key === 'revenue')?.value, revenue, 'revenue matches live Sales service');
assert.equal(data.revenue?.reduce((sum, row) => sum + row.value, 0), revenue, 'chart and KPI agree');
assert.ok(data.sales?.every(row => eligible.some(invoice => invoice.id === row.id)));
const balances = await inventoryService.listStockBalances(scope, { branchId: filters.branchId, permittedBranchIds: filters.permittedBranchIds });
assert.equal(data.stock?.reduce((sum, row) => sum + row.value, 0), balances.length);
assert.equal(data.lowStock?.length, Math.min(5, balances.filter(row => row.alertStatus !== 'healthy').length));
assert.equal(data.finance?.find(row => row.label === 'Receivables')?.value, accountingService.dashboard({ ...scope, permittedBranchIds: [scope.branchId] }, { branchId: scope.branchId }).receivables);
const single = await load({ permittedBranchIds: ['branch-001'] });
assert.equal(single.branches, undefined, 'single branch hides comparison');
const otherBranch = await load({ branchId: 'branch-002' });
assert.ok(otherBranch.sales?.every(row => !data.sales?.some(first => first.id === row.id)), 'branch transactions do not mix');
assert.ok(otherBranch.lowStock?.every(row => !data.lowStock?.some(first => first.id === row.id)), 'branch stock does not mix');
const otherTenant = await load({ tenantId: 'tenant-002' });
assert.ok(otherTenant.sales?.every(row => !data.sales?.some(first => first.id === row.id)), 'tenant sales isolation');
assert.ok(otherTenant.lowStock?.every(row => !data.lowStock?.some(first => first.id === row.id)), 'tenant stock isolation');
const none = await load({ permissions: [] });
assert.deepEqual(none.metrics, []);
assert.equal(none.finance, undefined); assert.equal(none.attendance, undefined); assert.equal(none.activity, undefined);
const hr = await load({ permissions: ['hr.employees.view'] });
assert.deepEqual(hr.metrics.map(row => row.key), ['employees']);
assert.equal(hr.attendance, undefined); assert.equal(hr.finance, undefined); assert.equal(hr.sales, undefined);
const inventory = await load({ permissions: ['inventory.view', 'inventory.stock.view'] });
assert.ok(inventory.stock); assert.equal(inventory.sales, undefined); assert.equal(inventory.finance, undefined);
const finance = await load({ permissions: ['finance.receivables.view'] });
assert.ok(finance.finance); assert.equal(finance.finance?.find(row => row.label === 'Payables'), undefined); assert.equal(finance.attendance, undefined);
const cashier = await load({ permissions: ['pos.view'] });
assert.ok(cashier.pos); assert.equal(cashier.finance, undefined); assert.equal(cashier.attendance, undefined);
assert.deepEqual(cashier.approvals, []);
const empty = await load({ dateFrom: '2000-01-01', dateTo: '2000-01-02' });
assert.equal(empty.metrics.find(row => row.key === 'revenue')?.value, 0); assert.deepEqual(empty.sales, []);
assert.notEqual(empty.metrics.find(row => row.key === 'revenue')?.value, revenue, 'date filter changes revenue');
assert.equal(empty.metrics.find(row => row.key === 'stock')?.value, data.metrics.find(row => row.key === 'stock')?.value, 'stock remains current state');
await assert.rejects(load({ branchId: 'unauthorized' }));
await assert.rejects(load({ tenantId: 'platform' }));
await assert.rejects(load({ dateFrom: '2026-12-31', dateTo: '2026-01-01' }));
await assert.rejects(load({ dateFrom: 'invalid' }));
await assert.rejects(load({ dateFrom: '2026-02-30' }));
assert.ok(data.sales?.every(row => row.to.startsWith('/sales/invoices?record=') && row.to.includes('&reference=')), 'sales links target existing detail dialogs');
assert.ok(data.purchases?.every(row => row.to.startsWith('/purchases/orders?record=') && row.to.includes('&reference=')), 'purchase links target existing detail dialogs');
const viewer = await load({ permissions: ['sales.view', 'purchase.view', 'hr.leave.view'] });
assert.deepEqual(viewer.approvals, [], 'view permission alone does not grant review queues');
const approver = await load({ permissions: ['sales.view', 'quotation.approve'] });
assert.ok(approver.approvals.every(row => row.module === 'Quotation'), 'approval action permissions restrict modules');
const original = salesService.listInvoices;
let reads = 0;
try {
  salesService.listInvoices = async () => { reads++; throw new Error('Simulated source failure'); };
  const restricted = await load({ permissions: ['hr.employees.view'] });
  assert.equal(reads, 0, 'no unauthorized service reads'); assert.deepEqual(restricted.errors, []);
  const failed = await load({ permissions: ['sales.view', 'hr.employees.view'] });
  assert.ok(failed.errors.includes('Sales')); assert.ok(failed.metrics.some(row => row.key === 'employees')); assert.equal(failed.revenue, undefined);
} finally { salesService.listInvoices = original; }
const now = new Date(2026, 9, 9, 12);
assert.equal(periodRange('today', now).dateFrom, '2026-10-09');
assert.equal(periodRange('week', now).dateFrom, '2026-10-05');
assert.equal(periodRange('month', now).dateFrom, '2026-10-01');
assert.equal(periodRange('quarter', now).dateFrom, '2026-10-01');
assert.equal(periodRange('year', now).dateFrom, '2026-01-01');
assert.deepEqual(previousRange('2026-10-01', '2026-10-09'), { dateFrom: '2026-09-22', dateTo: '2026-09-30' });
assert.equal(trend(0, 0).trend, 'neutral'); assert.equal(trend(100, 0).value, 'New activity');
console.log('Dashboard QA passed: source consistency, date ranges, branch and tenant isolation, permission gating, queues, empty data, and failure recovery.');
