import assert from 'node:assert/strict';
import { documentService as svc, MAX_DOCUMENT_BYTES, type DocumentScope } from '../src/features/documents/documentService';
import { TENANT_PERMISSIONS as P } from '../src/core/permissions/tenantPermissionConstants';

const scope: DocumentScope = { tenantId: 'tenant-001', branchId: 'branch-001', permittedBranchIds: ['branch-001'] };
const otherTenant: DocumentScope = { ...scope, tenantId: 'tenant-other' };
const otherBranch: DocumentScope = { ...scope, branchId: 'branch-002', permittedBranchIds: ['branch-002'] };
const actor = { id: 'qa', name: 'Document QA' };
const all = ['documents.view', 'documents.upload', 'documents.edit', 'documents.download', 'documents.archive', 'documents.categories', 'documents.view_sensitive'];
const viewOnly = [P.DOCUMENTS.VIEW];
const file = (name: string, type: string, body = 'sample') => new File([body], name, { type });

assert.throws(() => svc.list(scope, []), /documents.view/);
assert.equal(svc.list(otherTenant, all).total, 0);
assert.equal(svc.list(otherBranch, all).total, 0);
assert.throws(() => svc.validateFile(file('script.exe', 'application/octet-stream')));
assert.throws(() => svc.validateFile(file('wrong.pdf', 'image/png')));
assert.throws(() => svc.validateFile({ name: 'large.pdf', type: 'application/pdf', size: MAX_DOCUMENT_BYTES + 1 }));
assert.throws(() => svc.validateFile({ name: 'empty.pdf', type: 'application/pdf', size: 0 }));

// Dates relative to today, so the expiry and reminder checks never go stale.
const dayFromToday = (days: number) => new Date(Date.now() + days * 86400000).toISOString().slice(0, 10);
const expirySoon = dayFromToday(10);
const reminderPast = dayFromToday(-10);
const uploadInput = { title: 'QA contract', category: 'contract', description: 'Test', entityType: 'Customer' as const, entityId: 'cust-001', entityReference: 'CUST-0001', branchId: 'branch-001', expiryDate: expirySoon, reminderDate: reminderPast };
await assert.rejects(() => svc.upload(scope, viewOnly, actor, file('qa.pdf', 'application/pdf'), uploadInput), /documents.upload/);
await assert.rejects(() => svc.upload(scope, all, actor, file('qa.pdf', 'application/pdf'), { ...uploadInput, branchId: 'branch-002' }), /branch access/);
await assert.rejects(() => svc.upload(scope, all, actor, file('qa.pdf', 'application/pdf'), { ...uploadInput, reminderDate: dayFromToday(11) }), /Reminder date/);
await assert.rejects(() => svc.upload(scope, all.filter((permission) => permission !== P.DOCUMENTS.VIEW_SENSITIVE), actor, file('qa.pdf', 'application/pdf'), { ...uploadInput, sensitive: true }), /view_sensitive/);
let progress = 0;
const uploaded = await svc.upload(scope, all, actor, file('qa.pdf', 'application/pdf'), { ...uploadInput, sensitive: true }, (value) => { progress = value; });
assert.equal(progress, 100);
assert.equal(uploaded.versions.length, 1);
assert.equal(svc.list(scope, viewOnly).data.some((row) => row.id === uploaded.id), false);
assert.throws(() => svc.get(scope, viewOnly, uploaded.id));
assert.equal(svc.list(scope, all, { search: 'QA contract', category: 'contract', module: 'Customer', expiry: 'expiring' }).data.some((row) => row.id === uploaded.id), true);
assert.equal(svc.linkedPublic(scope, 'Customer', 'cust-001').some((row) => row.id === uploaded.id), false);
assert.equal(svc.linked(scope, all, 'Customer', 'cust-001').some((row) => row.id === uploaded.id), true);
assert.throws(() => svc.download(scope, viewOnly, actor, uploaded.id), /documents.download/);
svc.view(scope, all, actor, uploaded.id);
assert.equal(svc.download(scope, all, actor, uploaded.id).name, 'qa.pdf');
await assert.rejects(() => svc.addVersion(scope, viewOnly, actor, uploaded.id, file('qa-v2.pdf', 'application/pdf'), 'Reviewed'), /documents.edit/);
await svc.addVersion(scope, all, actor, uploaded.id, file('qa-v2.pdf', 'application/pdf'), 'Reviewed');
assert.equal(svc.get(scope, all, uploaded.id).versions.length, 2);
assert.equal(svc.download(scope, all, actor, uploaded.id, 1).name, 'qa.pdf');
svc.update(scope, all, actor, uploaded.id, { title: 'QA contract updated', category: 'contract', description: 'Updated', expiryDate: expirySoon, reminderDate: reminderPast, sensitive: true });
assert.equal(svc.get(scope, all, uploaded.id).title, 'QA contract updated');
assert.throws(() => svc.archive(scope, viewOnly, actor, uploaded.id), /documents.archive/);
svc.archive(scope, all, actor, uploaded.id);
assert.throws(() => svc.get(scope, all, uploaded.id), /archived/);
assert.equal(svc.list(scope, all, { archived: true }).data.some((row) => row.id === uploaded.id), true);
assert.ok(svc.audit(scope, all, uploaded.id).some((row) => row.action === 'Downloaded'));
assert.equal(svc.audit(scope, viewOnly, uploaded.id).length, 0);

assert.throws(() => svc.saveCategory(scope, viewOnly, actor, { name: 'QA', description: '', active: true }), /documents.categories/);
const category = svc.saveCategory(scope, all, actor, { name: 'QA category', description: 'Test category', active: true });
assert.equal(svc.categories(scope).some((row) => row.id === category.id), true);
svc.saveCategory(scope, all, actor, { id: category.id, name: category.name, description: category.description, active: false });
await assert.rejects(() => svc.upload(scope, all, actor, file('qa.pdf', 'application/pdf'), { ...uploadInput, category: category.id }), /active company document category/);
const reminder = await svc.upload(scope, all, actor, file('reminder.pdf', 'application/pdf'), { ...uploadInput, title: 'Reminder', sensitive: false });
assert.ok(svc.reminderHandoffs(scope, all).some((row) => row.id === reminder.id));
assert.equal(svc.reminderHandoffs(otherBranch, all).length, 0);
console.log('Document permissions, file validation, scope, versions, expiry, links, category, archive and audit checks passed.');
