const crudActions = ["view", "create", "edit", "delete"] as const;
const docActions = [...crudActions, "approve", "export", "print"] as const;

function buildPerms<T extends string>(
  module: string,
  resources: readonly T[],
  actions: readonly string[],
) {
  const result: Record<string, string> = {};
  for (const resource of resources) {
    for (const action of actions)
      result[`${resource}_${action}`.toUpperCase()] =
        `${module}.${resource}.${action}`;
  }
  return result;
}

